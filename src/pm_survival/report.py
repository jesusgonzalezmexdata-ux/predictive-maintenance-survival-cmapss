"""Deterministic evidence writers (TASK-004, SPEC-001 §4.4).

JSON is written with sorted keys and floats rounded to 6 decimals so two runs on
identical inputs are byte-identical (AC: determinism). Markdown renderers are
pure functions of the payload.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROUND = 6


def _round(obj: Any) -> Any:
    if isinstance(obj, float):
        return round(obj, ROUND)
    if isinstance(obj, dict):
        return {str(k): _round(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_round(v) for v in obj]
    if hasattr(obj, "item"):  # numpy scalar
        return _round(obj.item())
    if hasattr(obj, "tolist"):
        return _round(obj.tolist())
    return obj


def write_eval_json(path: Path, payload: dict) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    text = json.dumps(_round(payload), indent=2, sort_keys=True, ensure_ascii=True) + "\n"
    path.write_text(text, encoding="utf-8", newline="\n")


def _fmt(x: Any) -> str:
    return f"{x:.4f}" if isinstance(x, float) else str(x)


def render_eval_markdown(p: dict) -> str:
    w, cox, ph, sel, val = p["weibull"], p["cox"], p["ph_test"], p["selected_model"], p["validation"]
    lines = [
        f"# Evaluation — {p.get('subset', 'FD001')} survival / RUL baseline",
        "",
        "Status: EVIDENCE (not a promotion). Generated by `pm_survival`; SPEC-001 §4.4.",
        "",
        "## Split",
        "",
        f"- Grouped by unit; val_fraction = {p['split']['val_fraction']}, seed = {p['split']['seed']}",
        f"- Train units = {p['split']['n_train_units']}, validation units = {p['split']['n_val_units']}",
        "",
        "## Weibull (parametric baseline)",
        "",
        f"- shape β = {_fmt(w['shape'])}, scale λ = {_fmt(w['scale'])} → regime **{w['regime']}**",
        "",
        "## Cox proportional hazards",
        "",
        f"- Covariates ({len(cox['covariates'])}): {', '.join(cox['covariates'])}",
        f"- Train C-index = {_fmt(cox['train_concordance'])}",
        "",
        "## Proportional-hazards assumption (Schoenfeld residuals)",
        "",
        f"- Method: {ph['method']}, α = {ph['alpha']}, verdict: **{'holds' if ph['holds'] else 'VIOLATED'}**",
        "",
        "| covariate | p-value |",
        "|---|---|",
    ]
    for k in sorted(ph["p_values"]):
        lines.append(f"| {k} | {_fmt(ph['p_values'][k])} |")
    lines += [
        "",
        "## Selected model",
        "",
        f"- **{sel['kind']}** — {sel['reason']}",
        "",
        "## Validation (held-out units)",
        "",
        f"- C-index (primary, DEC-011) = {_fmt(val['concordance'])}",
        f"- Integrated Brier score = {_fmt(val['ibs'])}",
        "",
        "| horizon (cycles) | Brier |",
        "|---|---|",
    ]
    for k in sorted(val["brier"], key=lambda s: float(s)):
        lines.append(f"| {k} | {_fmt(val['brier'][k])} |")
    if "cost_policy" in p:
        cp = p["cost_policy"]
        lines += [
            "",
            "## Cost-optimal preventive replacement (illustrative, DEC-013)",
            "",
            f"- C_f / C_p = {cp['cost_ratio']} → t* = {_fmt(cp['t_star'])} cycles; expected cost rate at t* = {_fmt(cp['cost_rate_at_t_star'])}",
            f"- Reliability at t*: R(t*) = {_fmt(cp['reliability_at_t_star'])}",
            "",
            "This is baseline evidence, not a production recommendation.",
        ]
    return "\n".join(lines) + "\n"


def render_model_card(p: dict, open_decisions: list[str], limitations: list[str]) -> str:
    sel = p["selected_model"]
    lines = [
        f"# Model Card — {p.get('subset', 'FD001')} survival baseline ({sel['kind']})",
        "",
        "Status: EVIDENCE / IMPLEMENTED — **not VERIFIED, not PROMOTED**. Governance: SPEC-001, INTENT-446E2407EF97.",
        "",
        "## Intended use",
        "",
        "Baseline time-to-event evidence on NASA C-MAPSS FD001 to support later task-scoped work on cost-aware maintenance decisions. "
        "Outputs are **not a production recommendation**.",
        "",
        "## Data boundary",
        "",
        "- Source: DEC-003 archive declared in `data/raw/MANIFEST.json`; local extraction only (DEC-004).",
        "- Event: end of recorded run-to-failure trajectory (train). Test trajectories are right-censored; RUL truth is evaluation-only.",
        "- Covariates: early-life means (first 20 cycles) and per-unit slopes of operational settings / sensors; constant columns dropped.",
        "- Split: grouped by `unit_id` (no unit in both partitions).",
        "",
        "## Models",
        "",
        f"- Weibull: shape β = {_fmt(p['weibull']['shape'])}, scale λ = {_fmt(p['weibull']['scale'])}, regime {p['weibull']['regime']}.",
        f"- Cox PH on {len(p['cox']['covariates'])} covariates; PH check {p['ph_test']['method']} → {'holds' if p['ph_test']['holds'] else 'violated'}.",
        f"- Selected: **{sel['kind']}** — {sel['reason']}",
        "",
        "## Metrics (held-out units)",
        "",
        f"- C-index = {_fmt(p['validation']['concordance'])} (primary, DEC-011)",
        f"- IBS = {_fmt(p['validation']['ibs'])} over horizons {sorted(p['validation']['brier'], key=lambda s: float(s))} (DEC-012)",
        "",
        "## Limitations",
        "",
    ]
    lines += [f"- {l}" for l in limitations]
    lines += [
        "",
        "## Open decisions (verbatim from SPEC-001 §6)",
        "",
    ]
    lines += [f"- {d}" for d in open_decisions]
    lines += [
        "",
        "## Reproduction",
        "",
        "```bash",
        ".venv/Scripts/python -m pm_survival run --raw-dir data/raw/cmapss",
        "```",
    ]
    return "\n".join(lines) + "\n"


def write_text(path: Path, text: str) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
